import fs from "node:fs";
import path from "node:path";

export const REPORT = path.join("docs", "db-audit-report.md");

const HEADER = `# Database Audit Report

Generated by \`scripts/db-audit.ts\` and \`scripts/db-cleanup.ts\`. Secrets and personal data are masked; the connection string is never printed.
`;

/** Replace one named section of the report, keeping the others. */
export function writeReportSection(name: string, markdown: string): void {
  const start = `<!-- section:${name} -->`;
  const end = `<!-- /section:${name} -->`;
  const block = `${start}\n${markdown.trim()}\n${end}`;
  let text = fs.existsSync(REPORT) ? fs.readFileSync(REPORT, "utf8") : HEADER;
  const at = text.indexOf(start);
  if (at >= 0) {
    const stop = text.indexOf(end, at);
    text = text.slice(0, at) + block + text.slice(stop + end.length);
  } else {
    text = `${text.trimEnd()}\n\n${block}\n`;
  }
  fs.writeFileSync(REPORT, text.endsWith("\n") ? text : `${text}\n`);
}

/** Field names whose values are secrets or personal data. */
const SECRET_KEY = /(pass(word)?|secret|token|api[-_]?key|auth|uri|url|email|phone|user(name)?|ip(address)?|cookie|session)$/i;

/** Mask secrets, shorten long arrays and strings, so a sample document stays readable. */
export function maskSample(value: unknown, key = ""): unknown {
  if (key && SECRET_KEY.test(key)) return "***";
  if (typeof value === "string") {
    if (/mongodb(\+srv)?:\/\//i.test(value) || /@[\w.-]+\.\w+/.test(value)) return "***";
    return value.length > 80 ? `${value.slice(0, 77)}...` : value;
  }
  if (Array.isArray(value)) {
    const head = value.slice(0, 3).map((v) => maskSample(v));
    return value.length > 3 ? [...head, `... ${value.length - 3} more`] : head;
  }
  if (value instanceof Date) return value.toISOString();
  if (value && typeof value === "object") {
    if ((value as { _bsontype?: string })._bsontype === "ObjectId") return String(value);
    return Object.fromEntries(Object.entries(value as Record<string, unknown>).map(([k, v]) => [k, maskSample(v, k)]));
  }
  return value;
}
