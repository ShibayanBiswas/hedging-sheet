/**
 * Writes tests/fixtures/table-schema.json: every output table per tab with its exact headers, row labels and the cells
 * that show "-" because no value applies. Built from the Default Values run in mock mode; review and commit.
 *
 *   npx tsx scripts/build-table-schema.ts
 */
import fs from "node:fs";
import path from "node:path";

import { outputTables, specCells, specHeaders, specRowLabels } from "../lib/tables";
import { mockDefaultInputs, priceLikeTheApp } from "../tests/helpers/mock-market";

const r = priceLikeTheApp(mockDefaultInputs());
const tabs = Object.fromEntries(
  Object.entries(outputTables(r)).map(([tab, specs]) => [
    tab,
    specs.map((spec) => {
      const cells = specCells(spec);
      return {
        id: spec.id,
        title: spec.title,
        headers: specHeaders(spec),
        rowLabels: specRowLabels(spec),
        cellCount: cells.length,
        notApplicable: cells.filter((c) => c.text === "-").map((c) => c.key),
      };
    }),
  ]),
);

const out = path.join(process.cwd(), "tests", "fixtures", "table-schema.json");
fs.writeFileSync(
  out,
  `${JSON.stringify({ note: "Generated by scripts/build-table-schema.ts from the Default Values run in mock mode. Headers, row labels and not applicable cells per output table.", tabs }, null, 2)}\n`,
);
console.log("Wrote", path.relative(process.cwd(), out));
