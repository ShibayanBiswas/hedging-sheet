/**
 * Generates tests/fixtures/regression-expected.json from the engine with explicit dates and the pinned forward
 * growth of the saved sheet. Run once, review against the hand-checked tie-outs, then commit and leave frozen.
 *
 *   npx tsx scripts/build-regression-fixture.ts
 */
import fs from "node:fs";
import path from "node:path";

import { defaultInputs, seedMarketData } from "../lib/engine/defaults";
import { computeHedgingSheet } from "../lib/engine/hedging-sheet";

const inputs = { ...defaultInputs({ valuationDate: "2026-08-04", spot: 76799, dailyVol: 0.00895071 }), hedgeStrike: 76800 };
const options = {
  expiryDates: ["2030-01-31", "2030-04-25", "2030-07-25", "2030-10-31", "2031-01-30", "2031-04-24"],
  forwardGrowth: 0.055,
};
const r = computeHedgingSheet(inputs, seedMarketData(), options);
if (!r.ok) throw new Error(r.errors.map((e) => e.message).join("; "));
const g = r.productDescription.greeks;
const round = (v: number, dp = 10) => Math.round(v * 10 ** dp) / 10 ** dp;

const expected = {
  note: "Frozen. Generated by scripts/build-regression-fixture.ts and reviewed against the approved desk numbers. Do not regenerate unless the engine is meant to change.",
  inputs: { valuationDate: inputs.valuationDate, spot: inputs.spot, dailyVol: inputs.dailyVol, hedgeStrike: inputs.hedgeStrike },
  options,
  expected: {
    startLevel: r.structure.startLevel,
    actualInbuilt: round(r.summary.actualInbuilt),
    totalPremiumCr: round(r.summary.totalPremiumCr, 8),
    maturityCr: round(r.productDescription.maturityCr, 8),
    margin: round(r.summary.margin),
    hedgeExpiry: r.summary.hedgeExpiry,
    hedgeQuantity: round(g.hedgeQuantity, 6),
    totalDelta: round(g.totalDelta, 6),
    hedgePremiumCr: round(g.hedgePremiumCr, 8),
    optionsDelta: round(g.optionsDelta, 6),
    residualFutures: round(g.residualFutures, 6),
    weightedAverageVolatility: round(g.vegaWeightedVol),
    vegaCr: round(g.vegaCr, 8),
    weightedAverageForward: round(g.rhoWeightedForward),
    rhoCr: round(g.rhoCr, 8),
    leverage: g.leverage,
    targetLevel: round(g.targetLevel),
    zeroRowRequirementCr: round(r.markToMarket.zeroRow.totalRequirementCr, 8),
    legPrices: r.pricer.legs.filter((l) => l.expiryIndex === 0).map((l) => ({ strike: l.strike, price: round(l.price, 6) })),
  },
};

const out = path.join(process.cwd(), "tests", "fixtures", "regression-expected.json");
fs.writeFileSync(out, `${JSON.stringify(expected, null, 2)}\n`);
console.log("Wrote", path.relative(process.cwd(), out));
